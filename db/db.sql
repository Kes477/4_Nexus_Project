CREATE OR REPLACE FUNCTION FN_VALIDAR_ORDEN_SERVICIO() RETURNS TRIGGER AS $$
DECLARE
    v_rol_requerido  VARCHAR(20);
    v_requiere_campo CHAR(1);
    v_cliente_pedido INT;
    v_usuario_dir    INT;
    v_cliente_susc   INT;
    v_estado_susc    VARCHAR(20);
    v_max_mant       INT;
    v_usados_mant    INT;
BEGIN
    SELECT s.TIPO_ROL_REQUERIDO, s.REQUIERE_VISITA_CAMPO, p.ID_CLIENTE
      INTO v_rol_requerido, v_requiere_campo, v_cliente_pedido
      FROM TBL_DETALLES_PEDIDOS dp
      JOIN TBL_PEDIDOS p ON dp.ID_PEDIDO = p.ID_PEDIDO
      JOIN TBL_VARIANTES_PRODUCTOS vp ON dp.ID_VARIANTE = vp.ID_VARIANTE
      JOIN TBL_SERVICIOS s ON vp.ID_PRODUCTO = s.ID_SERVICIO
     WHERE dp.ID_DETALLE = NEW.ID_DETALLE_PEDIDO;

    IF v_rol_requerido = 'PILOTO' AND NEW.ID_PILOTO IS NULL THEN
        RAISE EXCEPTION 'El servicio requiere un PILOTO asignado.';
    ELSIF v_rol_requerido = 'TECNICO' AND NEW.ID_TECNICO IS NULL THEN
        RAISE EXCEPTION 'El servicio requiere un TECNICO asignado.';
    END IF;

    IF v_requiere_campo = 'S' AND NEW.ID_DIRECCION_EJECUCION IS NULL THEN
        RAISE EXCEPTION 'El servicio requiere visita a campo; debe indicar ID_DIRECCION_EJECUCION.';
    END IF;

    IF NEW.ID_DIRECCION_EJECUCION IS NOT NULL THEN
        SELECT ID_USUARIO INTO v_usuario_dir
          FROM TBL_DIRECCIONES
         WHERE ID_DIRECCION = NEW.ID_DIRECCION_EJECUCION;

        IF v_usuario_dir IS NULL OR v_usuario_dir <> v_cliente_pedido THEN
            RAISE EXCEPTION 'La dirección de ejecución del servicio debe pertenecer al cliente que compró el servicio.';
        END IF;
    END IF;

    IF NEW.ID_SUSCRIPCION_ACTIVA IS NOT NULL AND
       (TG_OP = 'INSERT' OR OLD.ID_SUSCRIPCION_ACTIVA IS NULL OR NEW.ID_SUSCRIPCION_ACTIVA <> OLD.ID_SUSCRIPCION_ACTIVA) THEN

        SELECT sa.ID_CLIENTE, sa.ESTADO_SUSCRIPCION
          INTO v_cliente_susc, v_estado_susc
          FROM TBL_SUSCRIPCIONES_ACTIVAS sa
         WHERE sa.ID_SUSCRIPCION_ACTIVA = NEW.ID_SUSCRIPCION_ACTIVA;

        IF v_cliente_susc <> v_cliente_pedido THEN
            RAISE EXCEPTION 'La suscripción activa no pertenece al mismo cliente que compró el servicio.';
        END IF;

        IF v_estado_susc <> 'ACTIVA' THEN
            RAISE EXCEPTION 'La suscripción asociada a la orden de servicio debe estar en estado ACTIVA.';
        END IF;

        SELECT sp.CANTIDAD_MANTENIMIENTOS_INCLUIDOS INTO v_max_mant
          FROM TBL_SUSCRIPCIONES_ACTIVAS sa
          JOIN TBL_SUSCRIPCIONES sp ON sa.ID_SUSCRIPCION_PLAN = sp.ID_SUSCRIPCION_PLAN
         WHERE sa.ID_SUSCRIPCION_ACTIVA = NEW.ID_SUSCRIPCION_ACTIVA;

        SELECT COUNT(*) INTO v_usados_mant
          FROM TBL_ORDENES_SERVICIO
         WHERE ID_SUSCRIPCION_ACTIVA = NEW.ID_SUSCRIPCION_ACTIVA
           AND ESTADO_SERVICIO <> 'CANCELADO'
           AND ID_ORDEN_SERVICIO IS DISTINCT FROM NEW.ID_ORDEN_SERVICIO;

        IF (v_usados_mant + 1) > v_max_mant THEN
            RAISE EXCEPTION 'Se ha superado el límite de mantenimientos incluidos en el plan de suscripción.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_VALIDAR_ORDEN_SERVICIO
BEFORE INSERT OR UPDATE OF ID_DETALLE_PEDIDO, ID_PILOTO, ID_TECNICO, ID_DIRECCION_EJECUCION, ID_SUSCRIPCION_ACTIVA
ON TBL_ORDENES_SERVICIO
FOR EACH ROW EXECUTE FUNCTION FN_VALIDAR_ORDEN_SERVICIO();

CREATE OR REPLACE FUNCTION FN_VALIDAR_SUSCRIPCION_ACTIVA() RETURNS TRIGGER AS $$
DECLARE
    v_cliente_pedido INT;
    v_producto_var   INT;
BEGIN
    SELECT p.ID_CLIENTE, vp.ID_PRODUCTO
      INTO v_cliente_pedido, v_producto_var
      FROM TBL_DETALLES_PEDIDOS dp
      JOIN TBL_PEDIDOS p ON dp.ID_PEDIDO = p.ID_PEDIDO
      JOIN TBL_VARIANTES_PRODUCTOS vp ON dp.ID_VARIANTE = vp.ID_VARIANTE
