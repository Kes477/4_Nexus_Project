    ID_CLIENTE          INT NOT NULL,
    FECHA_ACTUALIZACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT TBL_CARRITOS_PK PRIMARY KEY (ID_CARRITO),
    CONSTRAINT UQ_CARRITOS_CLIENTE UNIQUE (ID_CLIENTE),
    CONSTRAINT FK_CARRITOS_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES TBL_CLIENTES (ID_CLIENTE)
);

CREATE TABLE TBL_CARRITO_DETALLE (
    ID_CARRITO     INT NOT NULL,
    ID_VARIANTE    INT NOT NULL,
    TIPO_PRODUCTO  VARCHAR(20) NOT NULL,
    CANTIDAD       INT NOT NULL,
    FECHA_AGREGADO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT TBL_CARRITO_DETALLE_PK PRIMARY KEY (ID_CARRITO, ID_VARIANTE),
