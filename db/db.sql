-- SECCIÓN 1: SEGURIDAD, USUARIOS Y PERFILES

CREATE TABLE TBL_USUARIOS (
    ID_USUARIO          INT GENERATED ALWAYS AS IDENTITY NOT NULL,
    NO_IDENTIFICACION   VARCHAR(20) NOT NULL,
    CORREO_ELECTRONICO  VARCHAR(255) NOT NULL,
    CONTRASENA_HASH     VARCHAR(255) NOT NULL,
    NOMBRE              VARCHAR(100) NOT NULL,
    APELLIDO            VARCHAR(100) NOT NULL,
    TELEFONO            VARCHAR(20),
    FECHA_REGISTRO      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    FECHA_NACIMIENTO    DATE,
    ESTADO_CUENTA       CHAR(1) DEFAULT 'A' NOT NULL,
    FOTO_PERFIL_URL     VARCHAR(500),
    CONSTRAINT TBL_USUARIOS_PK PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_USUARIOS_IDENTIFICACION UNIQUE (NO_IDENTIFICACION),
    CONSTRAINT UQ_USUARIOS_CORREO UNIQUE (CORREO_ELECTRONICO),
    CONSTRAINT CHK_USUARIOS_ESTADO CHECK (ESTADO_CUENTA IN ('A', 'I', 'S', 'B'))
);

CREATE TABLE TBL_ROLES (
    ID_ROL      INT GENERATED ALWAYS AS IDENTITY NOT NULL,
    NOMBRE      VARCHAR(50) NOT NULL,
    DESCRIPCION VARCHAR(255),
    CONSTRAINT TBL_ROLES_PK PRIMARY KEY (ID_ROL),
    CONSTRAINT UQ_ROLES_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CHK_ROLES_VALIDOS CHECK (UPPER(NOMBRE) IN ('ADMINISTRADOR', 'CLIENTE', 'PILOTO', 'TECNICO', 'TÉCNICO', 'VENDEDOR'))
);

CREATE TABLE TBL_ROLES_USUARIOS (
    ID_USUARIO       INT NOT NULL,
    ID_ROL           INT NOT NULL,
    FECHA_ASIGNACION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT TBL_ROLES_USUARIOS_PK PRIMARY KEY (ID_USUARIO, ID_ROL),
    CONSTRAINT FK_ROL_USU_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TBL_USUARIOS (ID_USUARIO),
    CONSTRAINT FK_ROL_USU_ROL FOREIGN KEY (ID_ROL) REFERENCES TBL_ROLES (ID_ROL)
);

CREATE TABLE TBL_LOGS_ACCIONES (
    ID_LOG       INT GENERATED ALWAYS AS IDENTITY NOT NULL,
    ID_USUARIO   INT NULL,
    ACCION       VARCHAR(100) NOT NULL,
    DETALLE      TEXT,
    FECHA_ACCION TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    IP_ORIGEN    VARCHAR(45),
    CONSTRAINT TBL_LOGS_ACCIONES_PK PRIMARY KEY (ID_LOG),
    CONSTRAINT FK_LOGS_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES TBL_USUARIOS (ID_USUARIO)
);

CREATE TABLE TBL_CLIENTES (
    ID_CLIENTE      INT NOT NULL,
    NIVEL_FIDELIDAD VARCHAR(20),
    SALDO_PUNTOS    INT DEFAULT 0 NOT NULL,
    CONSTRAINT TBL_CLIENTES_PK PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT FK_CLIENTES_USUARIO FOREIGN KEY (ID_CLIENTE) REFERENCES TBL_USUARIOS (ID_USUARIO),
    CONSTRAINT CHK_CLIENTES_PUNTOS CHECK (SALDO_PUNTOS >= 0)
);

CREATE TABLE TBL_VENDEDORES (
    ID_VENDEDOR      INT NOT NULL,
    RTN_EMPRESA      VARCHAR(20) NOT NULL,
    NOMBRE_COMERCIAL VARCHAR(100) NOT NULL,
    SITIO_WEB        VARCHAR(255),
    COMISION_PACTADA NUMERIC(5,2) NOT NULL,
    CONSTRAINT TBL_VENDEDORES_PK PRIMARY KEY (ID_VENDEDOR),
    CONSTRAINT UQ_VENDEDORES_RTN UNIQUE (RTN_EMPRESA),
    CONSTRAINT FK_VENDEDORES_USUARIO FOREIGN KEY (ID_VENDEDOR) REFERENCES TBL_USUARIOS (ID_USUARIO),
    CONSTRAINT CHK_VENDEDORES_COMISION CHECK (COMISION_PACTADA >= 0 AND COMISION_PACTADA <= 100)
);

CREATE TABLE TBL_PILOTOS (
    ID_PILOTO                   INT NOT NULL,
    NUMERO_LICENCIA_AERONAUTICA VARCHAR(50) NOT NULL,
    HORAS_VUELO_ACUMULADAS      NUMERIC(8,2) DEFAULT 0 NOT NULL,
    TIPO_CERTIFICACION          VARCHAR(100),
    DISPONIBLE                  CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT TBL_PILOTOS_PK PRIMARY KEY (ID_PILOTO),
    CONSTRAINT UQ_PILOTOS_LICENCIA UNIQUE (NUMERO_LICENCIA_AERONAUTICA),
    CONSTRAINT FK_PILOTOS_USUARIO FOREIGN KEY (ID_PILOTO) REFERENCES TBL_USUARIOS (ID_USUARIO),
    CONSTRAINT CHK_PILOTOS_HORAS CHECK (HORAS_VUELO_ACUMULADAS >= 0),
    CONSTRAINT CHK_PILOTOS_DISPONIBLE CHECK (DISPONIBLE IN ('S', 'N'))
);

CREATE TABLE TBL_TECNICOS (
    ID_TECNICO               INT NOT NULL,
    ESPECIALIDAD_TECNICA     VARCHAR(100) NOT NULL,
    CERTIFICACION_FABRICANTE VARCHAR(100),
    DISPONIBLE               CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT TBL_TECNICOS_PK PRIMARY KEY (ID_TECNICO),
    CONSTRAINT FK_TECNICOS_USUARIO FOREIGN KEY (ID_TECNICO) REFERENCES TBL_USUARIOS (ID_USUARIO),
    CONSTRAINT CHK_TECNICOS_DISPONIBLE CHECK (DISPONIBLE IN ('S', 'N'))
);

