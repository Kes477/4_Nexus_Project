CREATE OR REPLACE FUNCTION FN_VALIDAR_RENOVACION_CLIENTE() RETURNS TRIGGER AS $$
DECLARE
    v_cliente_susc   INT;
    v_cliente_metodo INT;
BEGIN
    SELECT ID_CLIENTE INTO v_cliente_susc
      FROM TBL_SUSCRIPCIONES_ACTIVAS
     WHERE ID_SUSCRIPCION_ACTIVA = NEW.ID_SUSCRIPCION_ACTIVA;

    SELECT ID_CLIENTE INTO v_cliente_metodo
      FROM TBL_METODOS_PAGOS
     WHERE ID_METODO_PAGO = NEW.ID_METODO_PAGO;

    IF v_cliente_susc <> v_cliente_metodo THEN
        RAISE EXCEPTION 'El método de pago de la renovación no pertenece al cliente titular de la suscripción.';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_VALIDAR_RENOVACION_CLIENTE
BEFORE INSERT OR UPDATE OF ID_SUSCRIPCION_ACTIVA, ID_METODO_PAGO ON TBL_RENOVACIONES_SUSCRIPCION
FOR EACH ROW EXECUTE FUNCTION FN_VALIDAR_RENOVACION_CLIENTE();

CREATE OR REPLACE FUNCTION FN_VALIDAR_ENVIO_ARTICULOS() RETURNS TRIGGER AS $$
DECLARE
    v_cantidad_articulos INT;
BEGIN
    SELECT COUNT(*) INTO v_cantidad_articulos
      FROM TBL_DETALLES_PEDIDOS
     WHERE ID_PEDIDO = NEW.ID_PEDIDO
       AND TIPO_PRODUCTO = 'ARTICULO';

    IF v_cantidad_articulos = 0 THEN
        RAISE EXCEPTION 'No se puede generar un envío para un pedido sin artículos físicos.';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_VALIDAR_ENVIO_ARTICULOS
BEFORE INSERT OR UPDATE OF ID_PEDIDO ON TBL_ENVIOS
FOR EACH ROW EXECUTE FUNCTION FN_VALIDAR_ENVIO_ARTICULOS();

CREATE OR REPLACE FUNCTION FN_VALIDAR_RESENIA_COMPRA() RETURNS TRIGGER AS $$
DECLARE
    v_compras INT;
BEGIN
    IF NEW.COMPRA_VERIFICADA = 'S' THEN
        SELECT COUNT(*) INTO v_compras
          FROM TBL_PEDIDOS p
          JOIN TBL_DETALLES_PEDIDOS dp ON p.ID_PEDIDO = dp.ID_PEDIDO
          JOIN TBL_VARIANTES_PRODUCTOS vp ON dp.ID_VARIANTE = vp.ID_VARIANTE
         WHERE p.ID_CLIENTE = NEW.ID_CLIENTE
           AND vp.ID_PRODUCTO = NEW.ID_PRODUCTO
           AND p.ESTADO_PEDIDO IN ('PAGADO', 'EN_PROCESO', 'ENVIADO', 'ENTREGADO');

        IF v_compras = 0 THEN
            RAISE EXCEPTION 'No se puede marcar COMPRA_VERIFICADA = S si el cliente no ha adquirido el producto.';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_VALIDAR_RESENIA_COMPRA
BEFORE INSERT OR UPDATE OF COMPRA_VERIFICADA, ID_CLIENTE, ID_PRODUCTO ON TBL_RESENIAS
FOR EACH ROW EXECUTE FUNCTION FN_VALIDAR_RESENIA_COMPRA();