CREATE OR REPLACE FUNCTION FN_PROTEGER_SUBTIPO_ROL_USU() RETURNS TRIGGER AS $$
DECLARE
    v_nombre_rol VARCHAR(50);
    v_existe     INT := 0;
BEGIN
    SELECT UPPER(NOMBRE) INTO v_nombre_rol FROM TBL_ROLES WHERE ID_ROL = OLD.ID_ROL;

    IF v_nombre_rol = 'CLIENTE' THEN
        SELECT COUNT(*) INTO v_existe FROM TBL_CLIENTES WHERE ID_CLIENTE = OLD.ID_USUARIO;
    ELSIF v_nombre_rol = 'VENDEDOR' THEN
        SELECT COUNT(*) INTO v_existe FROM TBL_VENDEDORES WHERE ID_VENDEDOR = OLD.ID_USUARIO;
    ELSIF v_nombre_rol = 'PILOTO' THEN
        SELECT COUNT(*) INTO v_existe FROM TBL_PILOTOS WHERE ID_PILOTO = OLD.ID_USUARIO;
    ELSIF v_nombre_rol IN ('TECNICO', 'TÉCNICO') THEN
        SELECT COUNT(*) INTO v_existe FROM TBL_TECNICOS WHERE ID_TECNICO = OLD.ID_USUARIO;
    END IF;

    IF v_existe > 0 THEN
        RAISE EXCEPTION 'No se puede quitar el rol porque el usuario aún tiene un registro activo en la tabla de subtipo correspondiente.';
    END IF;
    
    IF TG_OP = 'DELETE' THEN 
        RETURN OLD; 
    ELSE 
        RETURN NEW; 
    END IF;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER TRG_PROTEGER_SUBTIPO_ROL_USU
BEFORE DELETE OR UPDATE OF ID_USUARIO, ID_ROL ON TBL_ROLES_USUARIOS
FOR EACH ROW EXECUTE FUNCTION FN_PROTEGER_SUBTIPO_ROL_USU();

