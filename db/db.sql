CREATE TABLE TBL_CUPONES (
    ID_CUPON         INT GENERATED ALWAYS AS IDENTITY NOT NULL,
    CODIGO           VARCHAR(50) NOT NULL,
    TIPO_DESCUENTO   CHAR(1) NOT NULL,
    VALOR_DESCUENTO  NUMERIC(12,2) NOT NULL,
    FECHA_INICIO     DATE NOT NULL,
    FECHA_EXPIRACION DATE NOT NULL,
    ACTIVO           CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT TBL_CUPONES_PK PRIMARY KEY (ID_CUPON),
    CONSTRAINT UQ_CUPONES_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CHK_CUPONES_TIPO CHECK (TIPO_DESCUENTO IN ('P', 'M')),
    CONSTRAINT CHK_CUPONES_VALOR CHECK (
        VALOR_DESCUENTO > 0 AND (TIPO_DESCUENTO = 'M' OR VALOR_DESCUENTO <= 100)
    ),
    CONSTRAINT CHK_CUPONES_ACTIVO CHECK (ACTIVO IN ('S', 'N')),
    CONSTRAINT CHK_CUPONES_FECHAS CHECK (FECHA_EXPIRACION >= FECHA_INICIO)
);

CREATE TABLE TBL_PEDIDOS (
    ID_PEDIDO         INT GENERATED ALWAYS AS IDENTITY NOT NULL,
    ID_CLIENTE        INT NOT NULL,
    FECHA_PEDIDO      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ESTADO_PEDIDO     VARCHAR(50) NOT NULL,
    ID_DIRECCION      INT NULL,
    SUBTOTAL          NUMERIC(12,2) NOT NULL,
    TOTAL_DESCUENTO   NUMERIC(12,2) DEFAULT 0 NOT NULL,
    COSTO_ENVIO       NUMERIC(12,2) DEFAULT 0 NOT NULL,
    TOTAL_IMPUESTOS   NUMERIC(12,2) DEFAULT 0 NOT NULL,
    TOTAL_FINAL       NUMERIC(12,2) NOT NULL,
    ID_CUPON_APLICADO INT NULL,
    CONSTRAINT TBL_PEDIDOS_PK PRIMARY KEY (ID_PEDIDO),
    CONSTRAINT FK_PED_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES TBL_CLIENTES (ID_CLIENTE),
    CONSTRAINT FK_PED_DIRECCION FOREIGN KEY (ID_DIRECCION) REFERENCES TBL_DIRECCIONES (ID_DIRECCION),
    CONSTRAINT FK_PED_CUPON FOREIGN KEY (ID_CUPON_APLICADO) REFERENCES TBL_CUPONES (ID_CUPON),
    CONSTRAINT CHK_PED_ESTADO CHECK (
        ESTADO_PEDIDO IN ('PENDIENTE', 'PAGADO', 'EN_PROCESO', 'ENVIADO', 'ENTREGADO', 'CANCELADO')
    ),
    CONSTRAINT CHK_PED_MONTOS CHECK (
        SUBTOTAL >= 0 AND TOTAL_DESCUENTO >= 0 AND TOTAL_DESCUENTO <= SUBTOTAL
        AND COSTO_ENVIO >= 0 AND TOTAL_IMPUESTOS >= 0 AND TOTAL_FINAL >= 0
    ),
    CONSTRAINT CHK_PED_CUPON_DESCUENTO CHECK (
        (ID_CUPON_APLICADO IS NULL AND TOTAL_DESCUENTO = 0) OR
        (ID_CUPON_APLICADO IS NOT NULL AND TOTAL_DESCUENTO >= 0)
    ),
    CONSTRAINT CHK_PED_TOTAL_ARITMETICO CHECK (
        TOTAL_FINAL = SUBTOTAL - TOTAL_DESCUENTO + COSTO_ENVIO + TOTAL_IMPUESTOS
    )
);

CREATE TABLE TBL_DETALLES_PEDIDOS (
    ID_DETALLE      INT GENERATED ALWAYS AS IDENTITY NOT NULL,
    ID_PEDIDO       INT NOT NULL,
    ID_VARIANTE     INT NOT NULL,
    TIPO_PRODUCTO   VARCHAR(20) NOT NULL,
    CANTIDAD        INT NOT NULL,
    PRECIO_UNITARIO NUMERIC(12,2) NOT NULL,
    SUBTOTAL_LINEA  NUMERIC(12,2) NOT NULL,
    CONSTRAINT TBL_DETALLES_PEDIDOS_PK PRIMARY KEY (ID_DETALLE),
    CONSTRAINT UQ_DET_PED_ID_TIPO UNIQUE (ID_DETALLE, TIPO_PRODUCTO),
    CONSTRAINT UQ_DET_PED_PEDIDO_VAR UNIQUE (ID_PEDIDO, ID_VARIANTE),
    CONSTRAINT FK_DETPED_PEDIDO FOREIGN KEY (ID_PEDIDO) REFERENCES TBL_PEDIDOS (ID_PEDIDO),
    CONSTRAINT FK_DETPED_VAR_TIPO FOREIGN KEY (ID_VARIANTE, TIPO_PRODUCTO)
        REFERENCES TBL_VARIANTES_PRODUCTOS (ID_VARIANTE, TIPO_PRODUCTO),
    CONSTRAINT CHK_DETPED_PRECIO CHECK (PRECIO_UNITARIO > 0),
    CONSTRAINT CHK_DETPED_SUBTOTAL CHECK (SUBTOTAL_LINEA = CANTIDAD * PRECIO_UNITARIO),
    CONSTRAINT CHK_DETPED_CANTIDAD_SEGUN_TIPO CHECK (
        (TIPO_PRODUCTO = 'ARTICULO' AND CANTIDAD >= 1) OR
        (TIPO_PRODUCTO IN ('SERVICIO', 'SUSCRIPCION') AND CANTIDAD = 1)
    )
);

CREATE TABLE TBL_METODOS_PAGOS (
